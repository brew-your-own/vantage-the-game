/**
 * Picks the campaign levels: codes whose terrain offers enough hiding places, with a hidden
 * start and room for five Relays. Writes src/core/campaignData.ts, easiest (most cover) first.
 *
 *   npm run curate
 */
import { writeFileSync } from 'node:fs';
import { keeperSightTiles, playerInLampSight } from '../src/core/keeper';
import { relaysForIndex } from '../src/core/levels';
import { DEFAULT_TERRAIN, generateTerrain } from '../src/core/terrain';
import { createWorld } from '../src/core/world';

const SCAN = 400;
const COUNT = 20;
const MIN_HIDDEN = 20;

interface Candidate {
  code: number;
  hidden: number;
}

const candidates: Candidate[] = [];
for (let code = 1; code <= SCAN; code++) {
  const terrain = generateTerrain({ ...DEFAULT_TERRAIN, seed: code });
  const world = createWorld(terrain, code, { relays: 5 });
  if (world.relays.length < 5 || playerInLampSight(world)) continue;
  const sight = keeperSightTiles(world);
  let hidden = 0;
  sight.forEach((v, i) => {
    if (!v && i !== world.keeper.cell && !world.relays.some((r) => r.cell === i)) hidden++;
  });
  if (hidden >= MIN_HIDDEN) candidates.push({ code, hidden });
}
if (candidates.length < COUNT) throw new Error(`only ${candidates.length} candidates`);

// Spread the picks over the range of cover, then order from most cover to least.
candidates.sort((a, b) => b.hidden - a.hidden);
const picks: Candidate[] = [];
for (let i = 0; i < COUNT; i++) picks.push(candidates[Math.round((i * (candidates.length - 1)) / (COUNT - 1))]);

const lines = picks.map((p, i) => `  ${p.code}, // ${i + 1}: ${p.hidden} hidden tiles, ${relaysForIndex(i)} Relays`);
writeFileSync(
  'src/core/campaignData.ts',
  `// Generated by scripts/curate.ts (npm run curate). Do not edit by hand.\nexport const CAMPAIGN_CODES: readonly number[] = [\n${lines.join('\n')}\n];\n`,
);
console.log(`${candidates.length} candidates; wrote ${COUNT} levels`);
