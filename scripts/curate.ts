/**
 * Picks the campaign levels: codes whose terrain offers enough hiding places, with a hidden
 * start and room for five Relays, spread over the range of cover. Then the playtest bot
 * plays each one at mid-campaign difficulty, and they are ordered by how long that takes,
 * quickest first. Writes src/core/campaignData.ts.
 *
 *   npm run curate
 */
import { writeFileSync } from 'node:fs';
import { hiddenTiles, isFairWorld } from '../src/core/fair';
import { difficulty, relaysForIndex } from '../src/core/levels';
import { playLevel } from './solver';
import { DEFAULT_TERRAIN, generateTerrain } from '../src/core/terrain';
import { createWorld } from '../src/core/world';

const SCAN = 400;
const COUNT = 20;

interface Candidate {
  code: number;
  hidden: number;
  /** Seconds the bot takes at mid difficulty (Infinity if it can't win). */
  seconds?: number;
}

const candidates: Candidate[] = [];
for (let code = 1; code <= SCAN; code++) {
  const terrain = generateTerrain({ ...DEFAULT_TERRAIN, seed: code });
  const world = createWorld(terrain, code, { relays: 5 });
  if (isFairWorld(world, 5)) candidates.push({ code, hidden: hiddenTiles(world) });
}
if (candidates.length < COUNT) throw new Error(`only ${candidates.length} candidates`);

// Spread the picks over the range of cover; skip any the bot cannot win.
candidates.sort((a, b) => b.hidden - a.hidden);
const picks: Candidate[] = [];
while (picks.length < COUNT) {
  const at = Math.round((picks.length * (candidates.length - 1)) / (COUNT - 1));
  const c = candidates.find((x, j) => j >= at && x.seconds === undefined);
  if (!c) throw new Error('ran out of winnable candidates');
  const play = playLevel(c.code, difficulty(0.5, 4), 5);
  c.seconds = play.won ? play.seconds : Infinity;
  if (play.won) picks.push(c);
}
picks.sort((a, b) => a.seconds! - b.seconds!);

const lines = picks.map(
  (p, i) => `  ${p.code}, // ${i + 1}: ${p.hidden} hidden tiles, bot ${p.seconds}s, ${relaysForIndex(i)} Relays`,
);
writeFileSync(
  'src/core/campaignData.ts',
  `// Generated by scripts/curate.ts (npm run curate). Do not edit by hand.\nexport const CAMPAIGN_CODES: readonly number[] = [\n${lines.join('\n')}\n];\n`,
);
console.log(`${candidates.length} candidates; wrote ${COUNT} levels`);
